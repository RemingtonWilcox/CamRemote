"""Generates app/CamRemote/SdkNames.g.cs from the Sony SDK headers.

Usage: python -I tools/gen_names.py <CRSDK header dir> <output .cs>
"""
import re
import sys
from pathlib import Path

hdr_dir, out_path = Path(sys.argv[1]), Path(sys.argv[2])

# Value enums the app shows to the user, keyed by the name used in C#.
VALUE_ENUMS = {
    "WhiteBalance": ("CrWhiteBalanceSetting", "CrWhiteBalance_"),
    "MovieFileFormat": ("CrFileFormatMovie", "CrFileFormatMovie_"),
    "MovieRecordingSetting": ("CrRecordingSettingMovie", "CrRecordingSettingMovie_"),
    "MovieFrameRate": ("CrRecordingFrameRateSettingMovie", "CrRecordingFrameRateSettingMovie_"),
    "FocusArea": ("CrFocusArea", "CrFocusArea_"),
    "FocusMode": ("CrFocusMode", "CrFocus_"),
    "ExposureProgram": ("CrExposureProgram", "CrExposure_"),
    "RecordingState": ("CrMovie_Recording_State", "CrMovie_Recording_State_"),
    "BatteryLevel": ("CrBatteryLevel", "CrBatteryLevel_"),
    "SlotStatus": ("CrSlotStatus", "CrSlotStatus_"),
    "MovieShootingMode": ("CrMovieShootingMode", "CrMovieShootingMode_"),
    "TouchFunction": ("CrFunctionOfTouchOperation", "CrFunctionOfTouchOperation_"),
    "TouchOperation": ("CrTouchOperation", "CrTouchOperation_"),
    "RecognitionTarget": ("CrRecognitionTarget", "CrRecognitionTarget_"),
    "EyeSelect": ("CrRightLeftEyeSelect", "CrRightLeftEyeSelect_"),
    "SubjectInAf": ("CrSubjectRecognitionInAF", "CrSubjectRecognitionInAF_"),
    "MonitorLut": ("CrMonitorLUTSetting", "CrMonitorLUT_"),
    "HdmiResolution": ("CrHDMIResolution", "CrHDMIResolution_"),
    "AudioRecording": ("CrAudioRecording", "CrAudioRecording_"),
    "WindNoise": ("CrWindNoiseReduction", "CrWindNoiseReduction_"),
}


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def parse_enums(text):
    enums, known = {}, {}
    for m in re.finditer(r"enum\s*(\w*)\s*(?::\s*[\w\s]+)?\{(.*?)\}", text, flags=re.S):
        name, body = m.group(1), m.group(2)
        members, nxt, skipping = [], 0, False
        for item in body.split(","):
            item = item.strip()
            if not item:
                continue
            if "=" in item:
                key, expr = (s.strip() for s in item.split("=", 1))
                # Drop C suffixes from number literals only (0x10u, 5UL), not from names like CrError_Level.
                expr = re.sub(r"\b(0[xX][0-9a-fA-F]+|\d+)[uUlL]+\b", r"\1", expr)
                try:
                    val = int(eval(expr, {"__builtins__": {}}, known))
                except Exception:
                    # Skipping it quietly would also shift every member after it that has no "=".
                    print(f"warning: couldn't work out {key} = {expr} in enum {name or '(unnamed)'}; skipped it and the members counting on from it",
                          file=sys.stderr)
                    skipping = True
                    continue
                skipping = False
            else:
                if skipping:
                    continue  # its value depends on the one that couldn't be worked out
                key, val = item, nxt
            known[key] = val
            members.append((key, val))
            nxt = val + 1
        enums[name or f"<anon{m.start()}>"] = members
    return enums


text = "".join(strip_comments(p.read_text(encoding="utf-8-sig", errors="replace"))
               for p in sorted(hdr_dir.glob("*.h")))
enums = parse_enums(text)


def pretty(name, prefix):
    s = name[len(prefix):] if name.startswith(prefix) else name
    return s.replace("_", " ").strip()


lines = [
    "// <auto-generated> by tools/gen_names.py from the Sony Camera Remote SDK headers. Do not edit.",
    "namespace CamRemote;",
    "",
    "public enum PropCode : uint",
    "{",
]
for key, val in enums["CrDevicePropertyCode"]:
    lines.append(f"    {key.removeprefix('CrDeviceProperty_')} = 0x{val:X},")
lines += ["}", "", "public static partial class SdkNames", "{"]

lines.append("    public static readonly Dictionary<string, Dictionary<long, string>> Values = new()")
lines.append("    {")
for cs_name, (enum_name, prefix) in VALUE_ENUMS.items():
    members = enums.get(enum_name)
    if not members:
        print(f"warning: enum {enum_name} not found", file=sys.stderr)
        continue
    lines.append(f'        ["{cs_name}"] = new()')
    lines.append("        {")
    seen = set()
    for key, val in members:
        if val in seen:
            continue
        seen.add(val)
        label = pretty(key, prefix).replace('"', '\\"')
        lines.append(f'            [0x{val:X}] = "{label}",')
    lines.append("        },")
lines.append("    };")
lines.append("")

lines.append("    public static readonly Dictionary<long, string> Errors = new()")
lines.append("    {")
seen = set()
for enum_name, members in enums.items():
    for key, val in members:
        if val not in seen and key.startswith(("CrError_", "CrWarning_")):
            seen.add(val)
            lines.append(f'        [0x{val:X}] = "{key}",')
lines += ["    };", "}", ""]

out_path.write_text("\n".join(lines), encoding="utf-8")

# The app explains Sony's errors by name (app/CamRemote/SdkCodes.cs), so a name it quotes that these headers
# don't have means that error only gets a general message. Say so at build time.
codes_cs = Path(__file__).resolve().parent.parent / "app" / "CamRemote" / "SdkCodes.cs"
if codes_cs.exists():
    all_names = {key for members in enums.values() for key, _ in members}
    wanted = sorted(set(re.findall(r'"(Cr(?:Error|Warning)_\w+)"', codes_cs.read_text(encoding="utf-8"))))
    for name in wanted:
        if name not in all_names:
            print(f"warning: {name} (used in SdkCodes.cs) is not in the SDK headers; "
                  "that error will get a general message. Find its new name in CrError.h and update SdkCodes.cs.",
                  file=sys.stderr)
print(f"wrote {out_path}: {len(enums['CrDevicePropertyCode'])} property codes")
